#!/usr/bin/env python3
"""Extract the design's own data arrays into an inventory the gate can assert against.

The `.dc.html` design carries its model as `const NAME = [...]` blocks. Those are the
CANONICAL sets — every screen, section, nav item, stage, filter and lane state the design
draws. Transcribing them by hand is what makes an inventory Class 1: a set the implementing
agent wrote is a set bounded by that agent's imagination. This reads them instead.
"""
import re, json, sys, pathlib

def blocks(src):
    out = {}
    for m in re.finditer(r'const ([A-Z_][A-Z_0-9]*)\s*=\s*([\[{])', src):
        name, i, depth = m.group(1), m.end() - 1, 0
        while i < len(src):
            if src[i] in "[{": depth += 1
            elif src[i] in "]}": depth -= 1
            if depth == 0: break
            i += 1
        out[name] = src[m.end() - 1:i + 1]
    return out

IDENTITY_KEYS = ("label", "name", "title", "key", "action", "ref", "id", "sub", "stage", "who", "k")

def strings(js):
    """The IDENTITY of each entry, not every quoted fragment.

    An array of objects is a set of things, and a thing is named by one of its fields. Taking
    every quoted string instead sweeps in costs, durations and CSS values, and an inventory
    that cannot tell an identity from a duration cannot say what is missing.
    """
    keyed = [v for k, a, b in re.findall(r"(\w+)\s*:\s*(?:'([^'\\]{1,60})'|\"([^\"\\]{1,60})\")", js)
             for v in (a, b) if v and k in IDENTITY_KEYS]
    if keyed:
        return keyed
    return [s for pair in re.findall(r"'([^'\\]{1,60})'|\"([^\"\\]{1,60})\"", js) for s in pair if s]

def main(path, out_dir):
    src = pathlib.Path(path).read_text()
    bs = blocks(src)
    STRUCTURAL = {"NAV", "STAGES", "FILTERS", "HINTS", "INSTANCES", "BASE", "SEAMS",
                  "MAIN_LANE", "SUB_LANES"}
    inv = {
        "source": pathlib.Path(path).name,
        "_structural": ("Sets the design's STRUCTURE — navigation, stages, filters, entry kinds. "
                        "Every identity in these must be drawn: they are the vocabulary a person "
                        "reads, and one missing is a screen that cannot say something the product "
                        "can. The rest are SAMPLE content — ticket titles, lane names, specific "
                        "refs — which a design illustrates rather than enumerates. A gate that "
                        "demands every sample row reports misses that are not misses, and a gate "
                        "that cries wolf is a gate nobody runs."),
        "structural": sorted(STRUCTURAL),
        "_doc": ("Generated by ref/extract.py from the design's own `const` blocks. "
                 "These are the identity lists the implementation is asserted against. "
                 "Regenerate after every design change; never hand-edit."),
        "sets": {},
    }
    for name, body in sorted(bs.items()):
        vals = strings(body)
        if vals:
            inv["sets"][name] = sorted(set(vals))
    inv["icons"] = sorted(set(re.findall(r'ph ph-([a-z-]+)', src)))
    inv["button_variants"] = sorted(set(re.findall(r'btn btn-([a-z]+)', src)))
    p = pathlib.Path(out_dir) / (pathlib.Path(path).stem.lower().replace(" ", "-") + ".inventory.json")
    p.write_text(json.dumps(inv, indent=2) + "\n")
    total = sum(len(v) for v in inv["sets"].values())
    print(f"{p}  {len(inv['sets'])} sets, {total} identities, "
          f"{len(inv['icons'])} icons, {len(inv['button_variants'])} button variants")

if __name__ == "__main__":
    for f in sys.argv[1:] or ["Dashboard.dc.html", "Ticket.dc.html"]:
        main(f, "ref")

